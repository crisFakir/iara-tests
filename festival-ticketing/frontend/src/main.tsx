// Register PWA Service Worker
if ('serviceWorker' in navigator) {
  const updateSW = registerSW({
    onNeedRefresh() {
      if (confirm('Nova versão disponível! Deseja atualizar?')) {
        updateSW(true);
      }
    },
    onOfflineReady() {
      console.log('App pronta para funcionar offline');
    },
  });
}

